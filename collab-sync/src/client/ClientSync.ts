/**
 * ClientSync — wraps Replica from Phase 1 and wires it to the relay.
 *
 * This is the primary integration point for Phase 3 (editor integration).
 * Everything the editor needs flows through this class:
 *
 *   editor → ClientSync.insert/delete   → Replica → outbox → relay
 *   relay  → ClientSync.onSocketMessage → Replica.receive → onOpsApplied → editor
 *
 * The Phase 1 Replica class is not modified in any way. All Phase 2 concerns
 * (serialisation, transport, offline persistence, presence, role enforcement,
 * and session reset) live in this class and its two collaborators
 * (ConnectionManager, OfflineQueue).
 *
 * ── Lifecycle ────────────────────────────────────────────────────────────────
 *
 *   new ClientSync(siteId, url, token)
 *     ↓
 *   await client.connect()
 *     → opens socket, sends JoinMessage with current vector clock snapshot
 *     → relay replays any missed ops, then sends WelcomeMessage
 *     → registers active sites in Replica.gc
 *     → auto-flushes OfflineQueue (queued offline ops sent to relay)
 *     ↓
 *   client.insert(offset, char)   ← editor calls this on keystroke
 *     → Replica.insert() generates op with correct clock sequence
 *     → op placed in outbox
 *     → drainOutboxAsync() picks it up next microtask
 *     → if online: send as OpMessage via ConnectionManager
 *     → if offline: persist to OfflineQueue
 *     ↓
 *   incoming OpMessage from relay
 *     → Replica.receive(op, senderSiteId) — CausalBuffer handles ordering
 *     → onOpsApplied fires with list of ops actually applied
 *     → editor updates CM6 view
 *     ↓
 *   socket closes unexpectedly
 *     → ConnectionManager starts exponential-backoff reconnect loop
 *     → further local edits go to OfflineQueue
 *     → on reconnect: relay replays inbound missed ops; OfflineQueue flushes outbound ops
 *     ↓
 *   incoming LogClearedMessage (after Owner calls reset())
 *     → Replica is replaced with a fresh empty instance
 *     → OfflineQueue is cleared
 *     → reset() promise resolves
 *
 * ── Invariants ───────────────────────────────────────────────────────────────
 *
 * 1. Every op generated by Replica.insert/delete is eventually sent to the
 *    relay exactly once. If the socket is offline at generation time, the op
 *    is persisted to OfflineQueue; on reconnect, the queue is drained before
 *    any new ops are sent so causal order is preserved.
 *
 * 2. Incoming ops are passed to Replica.receive(op, senderSiteId). The siteId
 *    comes from OpMessage.siteId (set by the relay from the authenticated
 *    session). The client never inspects op.afterId, op.nodeId, or op.clock —
 *    that is the CRDT layer's job. senderSiteId is required for CausalBuffer
 *    to advance the vector clock correctly on delete ops.
 *
 * 3. Outbound ops carry the sender's siteId in OpMessage.siteId. The relay
 *    verifies this against the authenticated session and rejects mismatches.
 */

import { Replica } from "crdt-engine";
import type {
  SiteId,
  RGAOperation,
  RGAInsert,
  RGADelete,
  VectorClockSnapshot,
} from "crdt-engine";
import type { LWWUpdate, LWWState } from "crdt-engine";

import {
  ConnectionManager,
  type ConnectionState,
  type ConnectionManagerOptions,
} from "./ConnectionManager";
import { OfflineQueue, type OfflineQueueOptions } from "./OfflineQueue";

import {
  encodeMessage,
  parseWireMessage,
  validateOpMessage,
  validateMetaMessage,
  makeOpMessage,
  makeMetaMessage,
  makeJoinMessage,
  makeMintTokenRequest,
  makeClearLogRequest,
  type WireMessage,
  type WelcomeMessage,
  type SiteJoinedMessage,
  type SiteLeftMessage,
  type ErrorMessage,
  type MintTokenResponse,
} from "../../shared/protocol";

import type { Role } from "../../shared/roles";

// ─── Options ────────────────────────────────────────────────────────────────

export interface ClientSyncOptions {
  /** Options forwarded to ConnectionManager (WebSocket impl, backoff). */
  connection?: ConnectionManagerOptions;
  /** Options forwarded to OfflineQueue (IndexedDB impl). */
  offlineQueue?: OfflineQueueOptions;
  /** If true, do not automatically flush offline queue on reconnect.
   *  Useful for tests that want to observe queue state. Default: false. */
  manualFlush?: boolean;
}

// ─── Events ─────────────────────────────────────────────────────────────────

export type OpsAppliedHandler = (ops: RGAOperation[]) => void;
export type MetaChangedHandler = (changed: LWWUpdate<unknown>[]) => void;
export type SiteJoinedHandler = (siteId: SiteId, role: Role) => void;
export type SiteLeftHandler = (siteId: SiteId) => void;
export type ConnectionChangeHandler = (state: ConnectionState) => void;
export type ErrorHandler = (err: ErrorMessage) => void;
export type WelcomeHandler = (activeSites: Array<{ siteId: SiteId; role: Role }>) => void;

// ─── Implementation ─────────────────────────────────────────────────────────

export class ClientSync {
  /**
   * The local CRDT state. Not readonly because reset() replaces it with a
   * fresh Replica when the Owner clears the session log.
   */
  replica: Replica;
  readonly siteId: SiteId;

  private readonly serverUrl: string;
  private readonly token: string;
  private readonly connectionManager: ConnectionManager;
  private readonly offlineQueue: OfflineQueue;
  private readonly manualFlush: boolean;

  private role: Role | null = null;
  private welcomed = false;
  private flushing = false;
  private mintResolvers: Map<SiteId, (token: string) => void> = new Map();
  /** Resolve callbacks for in-flight reset() calls, drained when log_cleared arrives. */
  private resetResolvers: Array<() => void> = [];

  // Event subscriptions — Phase 3 editor sets these
  onOpsApplied: OpsAppliedHandler | null = null;
  onMetaChanged: MetaChangedHandler | null = null;
  onSiteJoined: SiteJoinedHandler | null = null;
  onSiteLeft: SiteLeftHandler | null = null;
  onConnectionChange: ConnectionChangeHandler | null = null;
  onError: ErrorHandler | null = null;
  /** Fires once after WelcomeMessage is received, with the initial active-site roster. */
  onWelcome: WelcomeHandler | null = null;

  constructor(
    siteId: SiteId,
    serverUrl: string,
    token: string,
    options: ClientSyncOptions = {},
  ) {
    this.siteId = siteId;
    this.serverUrl = serverUrl;
    this.token = token;
    this.manualFlush = options.manualFlush ?? false;

    this.replica = new Replica(siteId);
    this.offlineQueue = new OfflineQueue(siteId, options.offlineQueue);
    this.connectionManager = new ConnectionManager(
      serverUrl,
      options.connection,
    );

    // Wire ConnectionManager callbacks
    this.connectionManager.onOpen = () => this.handleSocketOpen();
    this.connectionManager.onMessage = (raw) => this.handleSocketMessage(raw);
    this.connectionManager.onClose = () => this.handleSocketClose();
    this.connectionManager.onStateChange = (state) =>
      this.onConnectionChange?.(state);
  }

  // ─── Public API ───────────────────────────────────────────────────────────

  /**
   * Open the connection. Returns a promise that resolves when the
   * WelcomeMessage has been received, or rejects on fatal error.
   */
  async connect(): Promise<void> {
    await this.offlineQueue.open();

    return new Promise<void>((resolve, reject) => {
      const onWelcome = () => resolve();
      const onFatalError = (err: ErrorMessage) => {
        this.welcomeResolvers = null;
        reject(new Error(`${err.code}: ${err.message}`));
      };
      this.welcomeResolvers = { resolve: onWelcome, reject: onFatalError };

      this.connectionManager.connect();
    });
  }

  /** Disconnect cleanly. The session can be resumed by calling connect() again. */
  disconnect(): void {
    this.connectionManager.disconnect();
    this.welcomed = false;
  }

  /** Close the offline queue database. Call when the client is being torn down. */
  close(): void {
    this.disconnect();
    this.offlineQueue.close();
  }

  /**
   * Insert a character locally and broadcast the op to the relay.
   * Called by the editor on keystroke.
   *
   * If the connection is offline, the op is persisted to OfflineQueue and
   * will be delivered on reconnect.
   */
  insert(offset: number, value: string): RGAInsert {
    const op = this.replica.insert(offset, value);
    this.drainOutboxAsync();
    return op;
  }

  /**
   * Delete the character at the given offset locally and broadcast the op.
   * Returns null if offset is out of range.
   */
  delete(offset: number): RGADelete | null {
    const op = this.replica.delete(offset);
    if (op) this.drainOutboxAsync();
    return op;
  }

  /**
   * Update a metadata field (title, presence, etc.) and broadcast the
   * full LWW state snapshot. Returns immediately; transmission is async.
   */
  setMeta(field: string, value: unknown): void {
    this.replica.setMeta(field, value, Date.now());
    this.broadcastMetaAsync();
  }

  /**
   * Manually trigger an offline queue flush. Only relevant when
   * options.manualFlush was true. Normally the flush happens automatically
   * on reconnect.
   */
  async flushOfflineQueue(): Promise<number> {
    return this.flushQueue();
  }

  /**
   * Ask the relay to mint a token for a new site with the given role.
   * Only works when connected and the current role is Owner.
   * Resolves with the opaque token string that the new site can use to join.
   */
  mintToken(siteId: SiteId, role: Role): Promise<string> {
    if (!this.welcomed) {
      return Promise.reject(new Error("mintToken: not connected"));
    }
    return new Promise<string>((resolve, reject) => {
      this.mintResolvers.set(siteId, resolve);
      const sent = this.connectionManager.send(
        encodeMessage(makeMintTokenRequest(siteId, role)),
      );
      if (!sent) {
        this.mintResolvers.delete(siteId);
        reject(new Error("mintToken: failed to send request"));
      }
    });
  }

  // ─── Reads ────────────────────────────────────────────────────────────────

  getText(): string {
    return this.replica.getText();
  }

  getLength(): number {
    return this.replica.getLength();
  }

  getRole(): Role | null {
    return this.role;
  }

  getConnectionState(): ConnectionState {
    return this.connectionManager.getState();
  }

  async getOfflineQueueSize(): Promise<number> {
    return this.offlineQueue.size();
  }

  /**
   * Erase all ops currently stored in the offline queue.
   *
   * Lower-level than reset(). Only clears the persisted queue; does not
   * touch the relay log or the in-memory Replica.
   */
  async clearOfflineQueue(): Promise<void> {
    await this.offlineQueue.clear();
  }

  /**
   * Reset the entire session: tells the relay to clear its op log, then
   * resets the local Replica and offline queue once the relay confirms.
   *
   * Only the Owner role can do this. All currently connected clients will
   * also receive the reset signal and wipe their local state.
   *
   * Resolves when the relay has confirmed the reset (log_cleared received).
   */
  reset(): Promise<void> {
    if (!this.welcomed) {
      return Promise.reject(new Error("reset: not connected"));
    }
    return new Promise<void>((resolve, reject) => {
      this.resetResolvers.push(resolve);
      const sent = this.connectionManager.send(
        encodeMessage(makeClearLogRequest()),
      );
      if (!sent) {
        this.resetResolvers.pop();
        reject(new Error("reset: failed to send clear_log"));
      }
    });
  }

  // ─── Internal — socket events ─────────────────────────────────────────────

  private welcomeResolvers: {
    resolve: () => void;
    reject: (err: ErrorMessage) => void;
  } | null = null;

  private handleSocketOpen(): void {
    // Send the JoinMessage. The relay will respond with either Welcome
    // (success) or Error (failure).
    const clockSnapshot: VectorClockSnapshot = this.replica.getClockSnapshot();
    const joinMsg = makeJoinMessage(this.siteId, this.token, clockSnapshot);
    this.connectionManager.send(encodeMessage(joinMsg));
  }

  private handleSocketMessage(raw: string): void {
    const msg = parseWireMessage(raw);
    if (!msg) return; // malformed — silently drop

    switch (msg.kind) {
      case "welcome":
        this.handleWelcome(msg);
        break;
      case "op":
        this.handleOpMessage(msg);
        break;
      case "meta":
        this.handleMetaMessage(msg);
        break;
      case "site_joined":
        this.handleSiteJoined(msg);
        break;
      case "site_left":
        this.handleSiteLeft(msg);
        break;
      case "error":
        this.handleError(msg);
        break;
      case "token_minted":
        this.handleTokenMinted(msg);
        break;
      case "log_cleared":
        this.handleLogCleared();
        break;
      // "join", "mint_token", and "clear_log" are never received by clients
    }
  }

  private handleSocketClose(): void {
    this.welcomed = false;
    // In-flight welcomeResolvers is NOT rejected here — ConnectionManager
    // will retry and another welcome may still arrive. Only fatal errors
    // from the relay reject the resolver.
  }

  // ─── Internal — message handlers ──────────────────────────────────────────

  private handleWelcome(msg: WelcomeMessage): void {
    this.role = msg.role;
    this.welcomed = true;

    // Register all currently-active sites in our GC so delete ops will
    // eventually be collectable when every site has acked them.
    for (const { siteId } of msg.activeSites) {
      this.replica.gc.registerSite(siteId);
    }
    this.replica.gc.registerSite(this.siteId);

    // Notify the editor hook of the initial peer roster
    this.onWelcome?.(msg.activeSites);

    // Resolve the connect() promise
    if (this.welcomeResolvers) {
      this.welcomeResolvers.resolve();
      this.welcomeResolvers = null;
    }

    // Auto-flush the offline queue unless caller disabled it
    if (!this.manualFlush) {
      void this.flushQueue();
    }
  }

  private handleOpMessage(msg: unknown): void {
    const opMsg = validateOpMessage(msg as WireMessage);
    if (!opMsg) return; // malformed op message — drop

    // Pass to Replica.receive — CausalBuffer handles out-of-order delivery
    const applied = this.replica.receive(opMsg.op, opMsg.siteId);
    if (applied.length > 0) {
      this.onOpsApplied?.(applied);
    }
  }

  private handleMetaMessage(msg: unknown): void {
    const metaMsg = validateMetaMessage(msg as WireMessage);
    if (!metaMsg) return;

    const changed = this.replica.mergeMeta(metaMsg.state as LWWState<unknown>);
    if (changed.length > 0) {
      this.onMetaChanged?.(changed);
    }
  }

  private handleSiteJoined(msg: SiteJoinedMessage): void {
    this.replica.gc.registerSite(msg.siteId);
    this.onSiteJoined?.(msg.siteId, msg.role);
  }

  private handleSiteLeft(msg: SiteLeftMessage): void {
    // Do NOT deregister from GC immediately — a dropped connection may
    // reconnect with the same siteId. The GC will retain the site entry;
    // only a clean session termination should deregister. Phase 3 may
    // add a timeout policy for orphaned sites.
    this.onSiteLeft?.(msg.siteId);
  }

  private handleError(msg: ErrorMessage): void {
    // Fatal errors during connect() are surfaced via the rejected promise.
    // Only fire onError for non-fatal errors or errors outside the connect flow.
    const duringConnect = msg.fatal && this.welcomeResolvers !== null;
    if (!duringConnect) {
      this.onError?.(msg);
    }

    if (msg.fatal && this.welcomeResolvers) {
      this.welcomeResolvers.reject(msg);
      this.welcomeResolvers = null;
      // Stop the reconnect loop — a fatal auth error won't resolve with retries.
      this.connectionManager.disconnect();
    }
  }

  private handleTokenMinted(msg: MintTokenResponse): void {
    const resolve = this.mintResolvers.get(msg.siteId);
    if (resolve) {
      this.mintResolvers.delete(msg.siteId);
      resolve(msg.token);
    }
  }

  /**
   * Handle a LogClearedMessage broadcast by the relay after an Owner reset.
   *
   * Replaces the in-memory Replica with a fresh empty instance and clears the
   * IndexedDB offline queue so stale ops are not re-sent on reconnect. Any
   * pending reset() promises are resolved once the local state has been wiped.
   */
  private handleLogCleared(): void {
    this.replica = new Replica(this.siteId);
    void this.offlineQueue.clear();
    for (const resolve of this.resetResolvers.splice(0)) resolve();
  }

  // ─── Internal — outbox draining ───────────────────────────────────────────

  /**
   * Schedule an outbox drain on the next microtask. Batching through a
   * microtask prevents send() being called once per character during fast
   * typing — the outbox collects all synchronously-generated ops and
   * flushes them together.
   */
  private drainOutboxAsync(): void {
    queueMicrotask(() => void this.drainOutbox());
  }

  private async drainOutbox(): Promise<void> {
    const ops = this.replica.drainOutbox();
    if (ops.length === 0) return;

    const online =
      this.welcomed && this.connectionManager.getState() === "connected";

    if (online) {
      // Try to send each op directly. If any send fails mid-batch (socket
      // died between ops), the remaining ops go to the offline queue.
      for (let i = 0; i < ops.length; i++) {
        const op = ops[i]!;
        const sent = this.connectionManager.send(
          encodeMessage(makeOpMessage(this.siteId, op)),
        );
        if (!sent) {
          // Persist this op and the remaining ones; offline from here
          for (let j = i; j < ops.length; j++) {
            await this.offlineQueue.enqueue(ops[j]!);
          }
          return;
        }
      }
    } else {
      // Fully offline — persist all ops to the queue
      for (const op of ops) {
        await this.offlineQueue.enqueue(op);
      }
    }
  }

  private broadcastMetaAsync(): void {
    queueMicrotask(() => {
      if (!this.welcomed) return; // meta broadcast only when online
      const snapshot = this.replica.lww.snapshot();
      this.connectionManager.send(
        encodeMessage(makeMetaMessage(this.siteId, snapshot)),
      );
    });
  }

  /**
   * Drain the offline queue by sending each queued op, clearing them from
   * IndexedDB one by one. If the socket dies mid-flush, remaining ops
   * stay in the queue and will be flushed on the next successful reconnect.
   *
   * Returns the number of ops successfully flushed.
   */
  private async flushQueue(): Promise<number> {
    if (this.flushing) return 0; // prevent concurrent flushes
    this.flushing = true;

    let flushedCount = 0;
    try {
      const queued = await this.offlineQueue.getAll();

      for (const { seqNo, op } of queued) {
        if (this.connectionManager.getState() !== "connected") {
          // Socket died mid-flush — stop; remaining ops stay in queue
          break;
        }

        const sent = this.connectionManager.send(
          encodeMessage(makeOpMessage(this.siteId, op)),
        );

        if (!sent) break;

        // Successful send — remove this op from the queue.
        // clearUpTo(seqNo) also removes any earlier ops, which should
        // already be gone but this makes the invariant robust against
        // crashes between send and delete.
        await this.offlineQueue.clearUpTo(seqNo);
        flushedCount++;
      }
    } finally {
      this.flushing = false;
    }

    return flushedCount;
  }
}
