import { SiteId, RGAOperation } from "../types";
import { Replica } from "./Replica";

export type DeliveryOrder = "causal" | "random" | "reverse";

type PendingOp = {
  op: RGAOperation;
  from: SiteId;
};

/**
 * NetworkSim — in-memory network simulator for Phase 1 convergence testing.
 *
 * Connects a set of Replica instances and handles op delivery between them,
 * supporting causal, random, and reversed delivery orders for testing. The
 * partition/heal model mirrors the Phase 2 relay: a partitioned site is fully
 * isolated while offline, then both sides flush their queued ops on heal.
 *
 * ── Partition model ──────────────────────────────────────────────────────────
 * A partitioned site is fully isolated — it neither sends nor receives.
 *
 *   heldOutgoing  ops generated by the partitioned site while offline.
 *                 Delivered to all other sites on heal().
 *
 *   heldIncoming  ops generated by online sites while a site was partitioned.
 *                 Delivered to the partitioned site on heal().
 *
 * ── Note on senderSiteId ─────────────────────────────────────────────────────
 * NetworkSim calls replica.receive(op) without senderSiteId. This is
 * intentional: the simulator is used exclusively in Phase 1 tests where
 * convergence is verified across all delivery orders, and all ops are routed
 * through the same _deliverBatch() path where the sender (`from`) is available
 * but not threaded into receive(). Phase 2 (ClientSync) always passes
 * senderSiteId so the CausalBuffer can advance the clock correctly for delete
 * ops across sites.
 */
export class NetworkSim {
  private replicas: Map<SiteId, Replica>;

  /** Sites currently partitioned — neither send nor receive. */
  private partitioned: Set<SiteId>;

  /** Outgoing ops held for partitioned sites (generated while offline). */
  private heldOutgoing: Map<SiteId, PendingOp[]>;

  /** Incoming ops held for partitioned sites (generated by others while offline). */
  private heldIncoming: Map<SiteId, PendingOp[]>;

  private shuffleSeed: number;

  constructor(seed = 42) {
    this.replicas = new Map();
    this.partitioned = new Set();
    this.heldOutgoing = new Map();
    this.heldIncoming = new Map();
    this.shuffleSeed = seed;
  }

  // ─── Replica management ───────────────────────────────────────────────────

  /**
   * Register a new replica with the simulator. Mutually registers the new
   * site with all existing replicas' GC sets so tombstone collection is
   * accurate from the first operation.
   */
  addReplica(replica: Replica): void {
    for (const existing of this.replicas.values()) {
      existing.gc.registerSite(replica.siteId);
      replica.gc.registerSite(existing.siteId);
    }
    replica.gc.registerSite(replica.siteId);
    this.replicas.set(replica.siteId, replica);
  }

  /** Look up a replica by siteId. Returns undefined if not registered. */
  getReplica(siteId: SiteId): Replica | undefined {
    return this.replicas.get(siteId);
  }

  /** All siteIds currently registered with the simulator. */
  get siteIds(): SiteId[] {
    return [...this.replicas.keys()];
  }

  // ─── Partition / heal ─────────────────────────────────────────────────────

  /**
   * Fully isolate the given sites.
   * Their outgoing ops are queued in heldOutgoing.
   * Ops from online sites intended for them are queued in heldIncoming.
   */
  partition(siteIds: SiteId[]): void {
    for (const id of siteIds) {
      this.partitioned.add(id);
      if (!this.heldOutgoing.has(id)) this.heldOutgoing.set(id, []);
      if (!this.heldIncoming.has(id)) this.heldIncoming.set(id, []);
    }
  }

  /**
   * Heal all partitions.
   * 1. Deliver each partitioned site's outgoing ops to all online sites.
   * 2. Deliver all held incoming ops to the formerly partitioned sites.
   */
  heal(): void {
    const healing = [...this.partitioned];

    // Step 1: flush outgoing — deliver to all currently-online sites
    for (const siteId of healing) {
      const outgoing = this.heldOutgoing.get(siteId) ?? [];
      this._deliverBatch(outgoing, "causal", new Set()); // no partitions during flush
      this.heldOutgoing.delete(siteId);
    }

    // Step 2: flush incoming — deliver to the now-online sites
    for (const siteId of healing) {
      const incoming = this.heldIncoming.get(siteId) ?? [];
      for (const { op, from } of incoming) {
        const replica = this.replicas.get(siteId)!;
        const applied = replica.receive(op);
        for (const deliveredOp of applied) {
          if (deliveredOp.type === "delete") {
            this.replicas.get(from)?.gcAck(deliveredOp.targetId, siteId);
          }
        }
      }
      this.heldIncoming.delete(siteId);
    }

    this.partitioned.clear();
    this._runGCAll();
  }

  // ─── Automatic delivery ───────────────────────────────────────────────────

  /**
   * Collect all outbox ops from every online replica and deliver them.
   * Ops from online sites to partitioned sites are queued in heldIncoming.
   */
  step(order: DeliveryOrder = "causal"): number {
    const pending: PendingOp[] = [];

    for (const [siteId, replica] of this.replicas.entries()) {
      const ops = replica.drainOutbox();
      for (const op of ops) {
        if (this.partitioned.has(siteId)) {
          // Partitioned site generated an op — hold it in outgoing queue
          this.heldOutgoing.get(siteId)!.push({ op, from: siteId });
        } else {
          pending.push({ op, from: siteId });
        }
      }
    }

    this._deliverBatch(pending, order, this.partitioned);
    this._runGCAll();
    return pending.length;
  }

  /**
   * Run step() until no more ops are generated and all pending counts are zero.
   */
  runAll(order: DeliveryOrder = "causal", maxRounds = 1000): void {
    let rounds = 0;
    while (rounds < maxRounds) {
      const delivered = this.step(order);
      const anyPending = [...this.replicas.values()]
        .filter(r => !this.partitioned.has(r.siteId))
        .some(r => r.getPendingCount() > 0);
      if (delivered === 0 && !anyPending) break;
      rounds++;
    }
    if (rounds === maxRounds) {
      throw new Error(`NetworkSim.runAll: exceeded ${maxRounds} rounds`);
    }
  }

  // ─── Manual delivery ──────────────────────────────────────────────────────

  /**
   * Manually deliver a single op from `from` to all other replicas.
   * If `from` is partitioned, the op is queued in heldOutgoing instead.
   * Useful in tests that generate ops outside of a Replica's outbox.
   */
  broadcast(op: RGAOperation, from: SiteId, order: DeliveryOrder = "causal"): void {
    if (this.partitioned.has(from)) {
      this.heldOutgoing.get(from)!.push({ op, from });
      return;
    }
    this._deliverBatch([{ op, from }], order, this.partitioned);
    this._runGCAll();
  }

  // ─── Assertions ───────────────────────────────────────────────────────────

  /** Returns true if all online replicas have the same visible text. */
  assertConverged(): boolean {
    // Only compare online replicas — partitioned ones are intentionally behind
    const online = [...this.replicas.values()].filter(r => !this.partitioned.has(r.siteId));
    if (online.length === 0) return true;
    const texts = online.map(r => r.getText());
    return texts.every(t => t === texts[0]);
  }

  /**
   * Like assertConverged(), but throws with a diff-style message on failure.
   * Returns the converged text on success.
   */
  expectConverged(): string {
    if (this.assertConverged()) {
      const first = [...this.replicas.values()]
        .find(r => !this.partitioned.has(r.siteId));
      return first?.getText() ?? "";
    }
    const states = [...this.replicas.entries()]
      .map(([id, r]) => `  ${id}: "${r.getText()}"`)
      .join("\n");
    throw new Error(`Replicas have not converged:\n${states}`);
  }

  /** Returns true if all online replicas agree on the value of `field` in their LWW register. */
  assertLWWConverged(field: string): boolean {
    const online = [...this.replicas.values()].filter(r => !this.partitioned.has(r.siteId));
    const values = online.map(r => r.lww.get(field));
    return values.every(v => v === values[0]);
  }

  /** Returns true if ALL replicas (including partitioned ones) have the same text. */
  assertAllConverged(): boolean {
    const texts = [...this.replicas.values()].map(r => r.getText());
    return texts.every(t => t === texts[0]);
  }

  /** Returns a map of siteId → visible text for all replicas. Useful for debugging divergence. */
  dumpTexts(): Record<SiteId, string> {
    const out: Record<SiteId, string> = {};
    for (const [id, r] of this.replicas.entries()) out[id] = r.getText();
    return out;
  }

  /** Total number of ops buffered in CausalBuffer across all online replicas. */
  totalPending(): number {
    return [...this.replicas.values()]
      .filter(r => !this.partitioned.has(r.siteId))
      .reduce((s, r) => s + r.getPendingCount(), 0);
  }

  /** Number of ops queued for a partitioned site (outgoing + incoming). */
  queuedForSite(siteId: SiteId): number {
    return (this.heldOutgoing.get(siteId)?.length ?? 0) +
           (this.heldIncoming.get(siteId)?.length ?? 0);
  }

  /** Returns true if the given site is currently partitioned. */
  isPartitioned(siteId: SiteId): boolean {
    return this.partitioned.has(siteId);
  }

  // ─── Internal ─────────────────────────────────────────────────────────────

  /**
   * Deliver a batch of ops to all non-sender replicas.
   * Skips delivery to any site in `skipReceivers` (partitioned sites),
   * instead queuing ops in heldIncoming for those sites.
   */
  private _deliverBatch(
    pending: PendingOp[],
    order: DeliveryOrder,
    skipReceivers: Set<SiteId>
  ): void {
    let ordered: PendingOp[];
    switch (order) {
      case "reverse": ordered = [...pending].reverse(); break;
      case "random":  ordered = this._shuffle([...pending]); break;
      default:        ordered = pending;
    }

    for (const { op, from } of ordered) {
      for (const [siteId, replica] of this.replicas.entries()) {
        if (siteId === from) continue;

        if (skipReceivers.has(siteId)) {
          // Site is partitioned — queue for later delivery on heal
          this.heldIncoming.get(siteId)?.push({ op, from });
          continue;
        }

        const applied = replica.receive(op);
        for (const deliveredOp of applied) {
          if (deliveredOp.type === "delete") {
            this.replicas.get(from)?.gcAck(deliveredOp.targetId, siteId);
          }
        }
      }
    }
  }

  private _runGCAll(): void {
    for (const replica of this.replicas.values()) {
      replica.runGC();
    }
  }

  private _shuffle<T>(arr: T[]): T[] {
    for (let i = arr.length - 1; i > 0; i--) {
      this.shuffleSeed = (this.shuffleSeed * 1664525 + 1013904223) & 0xffffffff;
      const j = Math.abs(this.shuffleSeed) % (i + 1);
      [arr[i], arr[j]] = [arr[j]!, arr[i]!];
    }
    return arr;
  }
}